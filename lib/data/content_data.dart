];

List<Question> buildMatchGame() {
  final List<List<List<String>>> pools = List<List<List<String>>>.from(_matchPools)..shuffle(_r);
  final List<Question> qs = <Question>[];
  for (final List<List<String>> pool in pools.take(3)) {
    final List<List<String>> pairs = List<List<String>>.from(pool)..shuffle(_r);
    final List<List<String>> four = pairs.take(4).toList();
    qs.add(Question.match(
      'جفت\u200cها را به هم وصل کن',
      four.map((List<String> p) => p[0].replaceAll('^', '\u200c')).toList(),
      four.map((List<String> p) => p[1].replaceAll('^', '\u200c')).toList(),
    ));
  }
  return qs;
}
